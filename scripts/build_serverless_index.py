"""Precompute the lightweight retrieval index used by the Vercel functions.

Run from the project root whenever anything in ``ragg/`` changes:

    python scripts/build_serverless_index.py

It writes ``api/_index_data.py`` — a single Python module holding a zlib-
compressed, base64-encoded JSON blob. Embedding that data in a .py module
(rather than a .json file) means Vercel's Python bundler always ships it with
every function, with no runtime filesystem reads and no third-party packages.

Only the Python standard library is needed here and at function runtime.
"""
from __future__ import annotations

import base64
import hashlib
import json
import math
import sys
import zlib
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "api"))

from _text import (  # noqa: E402
    load_corpus,
    merge_fragments,
    recursive_chunk,
    tokenize,
)

CHUNK_SIZE = 300
CHUNK_OVERLAP = 50


def corpus_signature(corpus_dir: Path) -> str:
    digest = hashlib.sha256()
    for path in sorted(corpus_dir.glob("*.txt")):
        digest.update(path.name.encode("utf-8"))
        digest.update(hashlib.md5(path.read_bytes()).hexdigest().encode("ascii"))
    return digest.hexdigest()


def build() -> dict:
    corpus_dir = ROOT / "ragg"
    docs = load_corpus(corpus_dir)

    sources: list[str] = []
    texts: list[str] = []
    doc_meta: list[list] = []
    for name, text in docs.items():
        doc_meta.append([name, len(text)])
        for piece in merge_fragments(
            recursive_chunk(text, CHUNK_SIZE, CHUNK_OVERLAP)
        ):
            sources.append(name)
            texts.append(piece)

    n = len(texts)
    if not n:
        raise RuntimeError("The corpus produced no chunks.")

    doc_names = [row[0] for row in doc_meta]
    source_ids = [doc_names.index(s) for s in sources]

    counts: list[Counter] = []
    df: Counter = Counter()
    for text in texts:
        c = Counter(tokenize(text))
        counts.append(c)
        df.update(c.keys())

    # sklearn-style smoothed idf, sublinear tf. Both sides (chunks and query)
    # use this same formula so the dot product is a real cosine similarity.
    idf = {t: math.log((1 + n) / (1 + d)) + 1.0 for t, d in df.items()}

    norms: list[float] = []
    doc_lengths: list[int] = []
    postings: dict[str, list[list[int]]] = {}
    for i, c in enumerate(counts):
        norm = 0.0
        for term, tf in c.items():
            w = (1.0 + math.log(tf)) * idf[term]
            norm += w * w
            postings.setdefault(term, []).append([i, tf])
        norms.append(round(math.sqrt(norm), 6))
        doc_lengths.append(sum(c.values()))

    return {
        "v": 1,
        "built_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "signature": corpus_signature(corpus_dir),
        "docs": doc_meta,
        "chunks": [[source_ids[i], texts[i]] for i in range(n)],
        "n": n,
        "avgdl": round(sum(doc_lengths) / n, 4),
        "idf": {t: round(v, 6) for t, v in idf.items()},
        "norm": norms,
        "dl": doc_lengths,
        "postings": postings,
    }


def render(index: dict) -> str:
    raw = json.dumps(index, separators=(",", ":"), ensure_ascii=False).encode("utf-8")
    blob = base64.b64encode(zlib.compress(raw, 9)).decode("ascii")
    lines = [blob[i : i + 100] for i in range(0, len(blob), 100)]
    body = "".join(f'    "{line}"\n' for line in lines)
    return (
        '"""AUTO-GENERATED by scripts/build_serverless_index.py — do not edit.\n\n'
        f"Corpus signature {index['signature'][:16]} | built {index['built_at']} | "
        f"{index['n']} chunks from {len(index['docs'])} documents.\n"
        'Regenerate with: python scripts/build_serverless_index.py\n"""\n'
        "PAYLOAD = (\n" + body + ")\n"
    )


def main() -> None:
    index = build()
    out = ROOT / "api" / "_index_data.py"
    out.write_text(render(index), encoding="utf-8")
    raw_bytes = len(json.dumps(index, separators=(",", ":"), ensure_ascii=False).encode("utf-8"))
    print(f"documents : {len(index['docs'])}")
    print(f"chunks    : {index['n']}")
    print(f"vocabulary: {len(index['idf'])} terms")
    print(f"json      : {raw_bytes / 1024:.1f} KiB")
    print(f"module    : {out.stat().st_size / 1024:.1f} KiB -> {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
